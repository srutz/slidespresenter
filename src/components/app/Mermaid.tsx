import { useEffect, useId, useState } from "react";

/** Renders a mermaid diagram definition as inline SVG (mermaid is loaded lazily). */
export function Mermaid({ chart }: { chart: string }) {
	const id = `mermaid-${useId().replace(/[^a-zA-Z0-9]/g, "")}`;
	const [svg, setSvg] = useState<string | null>(null);
	const [error, setError] = useState<string | null>(null);

	useEffect(() => {
		let cancelled = false;
		setError(null);
		import("mermaid")
			.then(async ({ default: mermaid }) => {
				mermaid.initialize({
					startOnLoad: false,
					theme: "base",
					themeVariables: {
						darkMode: false,
						background: "#ffffff",
						primaryColor: "#eef2ff",
						primaryTextColor: "#111827",
						primaryBorderColor: "#6366f1",
						lineColor: "#4b5563",
						secondaryColor: "#f3f4f6",
						tertiaryColor: "#ffffff",
						edgeLabelBackground: "#ffffff",
					},
				});
				const { svg } = await mermaid.render(id, chart);
				if (!cancelled) setSvg(svg);
			})
			.catch((e) => {
				if (!cancelled) setError(String(e?.message ?? e));
				document.getElementById(`d${id}`)?.remove();
			});
		return () => {
			cancelled = true;
		};
	}, [chart, id]);

	if (error) {
		return (
			<pre className="my-3 text-sm text-red-600 whitespace-pre-wrap">
				Mermaid error: {error}
			</pre>
		);
	}
	if (!svg) return <div className="my-3 min-h-16" />;
	return (
		<div
			className="mermaid-diagram my-3 flex justify-center bg-white text-gray-900 [color-scheme:light]"
			// biome-ignore lint/security/noDangerouslySetInnerHtml: svg generated by mermaid
			dangerouslySetInnerHTML={{ __html: svg }}
		/>
	);
}
